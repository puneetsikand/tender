import Foundation

/// Workflows on disk (PLAN §8.3): `<name>.pfflow` (JSON, the source of truth) plus a generated,
/// read-only `<name>.md` description next to it that the app never parses.
public struct WorkflowStore: Sendable {
    public let folder: URL

    /// `~/Library/Application Support/PhotoFerry/Workflows`; `PF_WORKFLOWS` overrides it.
    public static var defaultFolder: URL {
        if let override = ProcessInfo.processInfo.environment["PF_WORKFLOWS"] {
            return URL(fileURLWithPath: override, isDirectory: true)
        }
        return URL.applicationSupportDirectory.appending(path: "PhotoFerry/Workflows", directoryHint: .isDirectory)
    }

    public init(folder: URL = WorkflowStore.defaultFolder) {
        self.folder = folder
    }

    public static func encode(_ w: Workflow) throws -> Data {
        let e = JSONEncoder()
        e.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        return try e.encode(w) + Data("\n".utf8)
    }

    public static func decode(_ data: Data) throws -> Workflow {
        try JSONDecoder().decode(Workflow.self, from: data)
    }

    /// File-safe base name for a workflow name.
    public static func fileName(for name: String) -> String {
        Template.sanitize(name) ?? "workflow"
    }

    public func list() throws -> [(url: URL, workflow: Workflow?)] {
        let urls = (try? FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: nil)) ?? []
        return urls.filter { $0.pathExtension == "pfflow" }.sorted { $0.lastPathComponent < $1.lastPathComponent }
            .map { ($0, try? Self.decode(Data(contentsOf: $0))) }
    }

    /// Loads by path, or by name from the store.
    public func load(_ nameOrPath: String) throws -> Workflow {
        let direct = URL(fileURLWithPath: (nameOrPath as NSString).expandingTildeInPath)
        let url = FileManager.default.fileExists(atPath: direct.path) ? direct
            : folder.appending(path: Self.fileName(for: nameOrPath) + ".pfflow")
        return try Self.decode(Data(contentsOf: url))
    }

    /// Validates, then writes the JSON and its Markdown description atomically.
    @discardableResult
    public func save(_ w: Workflow) throws -> URL {
        try Planner.validate(w)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        let base = folder.appending(path: Self.fileName(for: w.name))
        let json = base.appendingPathExtension("pfflow")
        try Self.encode(w).write(to: json, options: .atomic)
        try Data(WorkflowDescriber.markdown(w).utf8).write(to: base.appendingPathExtension("md"), options: .atomic)
        return json
    }
}

/// Plain-language description of a workflow, for people. Generated; never parsed back.
public enum WorkflowDescriber {
    public static func markdown(_ w: Workflow) -> String {
        var md = "# \(w.name)\n\n"
        md += "_Generated by PhotoFerry from `\(WorkflowStore.fileName(for: w.name)).pfflow`. Edit the workflow, not this file._\n\n"
        md += "- **Verify:** \(verifyText(w.verify))\n"
        md += "- **Capture times without a time zone:** read as \(w.timeZone ?? "the Mac's time zone")\n"
        md += "- **Extensions:** \(w.extensionCase == .original ? "kept as on the card" : w.extensionCase.rawValue + "case")\n\n"
        md += "## Destinations\n\n"
        for d in w.destinations { md += "- **\(d.name)** (`\(d.id)`): `\(d.root)`\n" }
        md += "\n## Routes\n\nEach file goes to the first route that matches it. Sidecar files (XMP, THM …) go with their photo or clip.\n\n"
        for (i, r) in w.routes.enumerated() {
            md += "\(i + 1). **\(r.name)**: \(matchText(r.match))"
            if r.skip { md += " → left on the card\n"; continue }
            let names = r.destinations.map { id in w.destinations.first { $0.id == id }?.name ?? id }
            md += " → `\(r.folder)/\(r.fileName).<ext>` in \(names.joined(separator: " and "))\n"
        }
        md += "\nFiles no route matches stay on the card.\n"
        return md
    }

    static func verifyText(_ m: VerifyMode) -> String {
        switch m {
        case .size: "size check only"
        case .hash: "every copy is re-read from disk and its SHA-256 compared with the card's"
        case .paranoid: "as hash, and the card is read twice to catch an unreliable reader"
        case .bytes: "every copy is compared byte for byte with a second read of the card"
        }
    }

    static func matchText(_ m: Workflow.Match) -> String {
        var parts: [String] = []
        if let k = m.kinds { parts.append(k.map { $0.rawValue.uppercased() }.joined(separator: "/") + " files") }
        if let e = m.extensions { parts.append("extension " + e.map { "." + $0.lowercased() }.joined(separator: " or ")) }
        if let c = m.cameraModels { parts.append("from a camera named " + c.map { "\"\($0)\"" }.joined(separator: " or ")) }
        if let s = m.bodySerials { parts.append("from body serial " + s.joined(separator: " or ")) }
        return parts.isEmpty ? "all files" : parts.joined(separator: ", ")
    }
}
